/// @internal
/// @brief Noexcept-safe execute expression for friend operator noexcept specifiers.
///
/// Equivalent to @c SCL_FRIEND_EXECUTE_OVERRIDED but uses
/// @c std::declval\<s_c_l_executor_type cv_ref\>() in place of the real executor
/// obtained via @c executor_trait\<Wrapper\>.  This avoids instantiating
/// @c executor_trait while the wrapper class is still incomplete (GCC 13 evaluates
/// friend-function noexcept specifiers eagerly at class-definition time).
/// Safe in @c noexcept(noexcept(...)) because noexcept is an unevaluated context.
///
/// @param op     The C++ operator token sequence (e.g. @c operator\ +).
/// @param cv_ref cv-ref qualifiers of @p scl_self.
#define SCL_FRIEND_EXECUTE_OVERRIDED_NX(op, cv_ref)                                \
    s_c_l_executor_type::execute(::std::declval<s_c_l_executor_type cv_ref>(),     \
        [](auto && scl_e, ScLArgs &&... values) -> decltype(auto) {                \
        return s_c_l_executor_type::access(::std::forward<decltype(scl_e)>(scl_e)) \
            .op(::scl::wrapper_cast(::std::forward<ScLArgs>(values))...);          \
    }, ::std::declval<s_c_l_executor_type cv_ref>(), ::std::forward<ScLArgs>(scl_args)...)

